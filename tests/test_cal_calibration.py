def attempt_resampled_interval(
    cell: Sequence[Any], *, resamples: int = RESAMPLES, seed: int = 20260922
) -> tuple[float, float]:
    """**Mutant M2's estimator, written out here so the control is real.**  Resamples the
    cell's *attempts* with replacement, ignoring which task each came from.  This is the wrong
    interval: it treats a task's five correlated attempts as five independent observations, so
    it is narrower than the truth, and it is narrower in the direction that flatters the card.
    The test that uses it names which of the two is published."""
    rng = random.Random(seed)
    rows = [bool(r.strict) for r in cell]
    out: list[float] = []
    for _ in range(resamples):
        draw = [rows[rng.randrange(len(rows))] for _ in range(len(rows))]
        out.append(sum(draw) / len(draw))
    out.sort()
    return out[int(0.025 * (len(out) - 1))], out[int(0.975 * (len(out) - 1))]


def width(interval: tuple[float, float]) -> float:
    return interval[1] - interval[0]


@pytest.mark.parametrize("counts", [(2, 3, 4), (1, 4, 5), (0, 2, 4, 5)])
def test_cal9_1_the_bootstrap_reproduces_the_exact_enumerated_distribution(
    counts: Sequence[int],
) -> None:
    """**CAL9 against an enumerated answer, not against the build.**  At S = 3 the clustered
    resampling distribution is 27 equally likely points and at S = 4 it is 256, so both
    quantiles have closed answers.  Measured across five seeds: the Monte Carlo bootstrap
    reproduces them exactly, so this asserts equality.

    `(2, 3, 4)` is the load-bearing case -- its interval is (0.4, 0.8), an interior answer.
    A fixture whose interval is (0.0, 1.0) would be satisfied by any estimator that returns
    the extremes."""
    exact = exact_cluster_bootstrap(counts)
    assert len(exact) == len(counts) ** len(counts)
    low, high = cal().cluster_bootstrap(
        cal().scored(cell_from(counts)), cal().pass_at_1, resamples=RESAMPLES, seed=7
    )
    assert low == pytest.approx(exact_quantile(exact, 0.025), abs=1e-9)
    assert high == pytest.approx(exact_quantile(exact, 0.975), abs=1e-9)
    # and the interval must contain the point estimate it is an interval for
    assert low <= expect_pass_at_1(counts) <= high
    # ... and must not be the trivial whole range, or it would pin nothing
    assert (low, high) != (0.0, 1.0)


def test_cal9_3_the_seed_is_load_bearing() -> None:
    """The seed reaches the interval: if it did nothing, a reproducibility check would pass
    on a constant and pin nothing.

    Asserted over a **set** of seeds rather than a pair.  pass@1 on S = 12 tasks takes only
    61 distinct values, so its 2.5 and 97.5 quantiles genuinely coincide for many pairs of
    seeds -- measured: seeds 11 and 12 give the identical interval.  A pairwise "different
    seed, different interval" test is therefore false, and asserting it would be pinning an
    accident of the fixture rather than an invariant."""
    scored = cal().scored(heterogeneous())
    seen = {
        cal().cluster_bootstrap(scored, cal().pass_at_1, resamples=RESAMPLES, seed=s)
        for s in range(20)
    }
    assert len(seen) > 1, seen


def test_cal9_4_resampling_tasks_is_strictly_wider_than_resampling_attempts() -> None:
    """**CAL9's named control, and mutant M2's test.**  On a fixture with real task
    heterogeneity, the clustered interval is strictly wider than the attempt-resampled one,
    because a task's attempts are not independent observations of the cell.  **The published
    interval is the clustered one** -- this test is where that is written down."""
    cell = heterogeneous()
    clustered = cal().cluster_bootstrap(
        cal().scored(cell), cal().pass_at_1, resamples=RESAMPLES, seed=20260922
    )
    by_attempt = attempt_resampled_interval(cell, resamples=RESAMPLES, seed=20260922)
    assert width(clustered) > width(by_attempt), (clustered, by_attempt)
    # not a hair's breadth: the whole point is that the wrong one is visibly optimistic
    assert width(clustered) > 1.25 * width(by_attempt), (clustered, by_attempt)


def test_cal9_7_each_bound_is_a_value_some_resample_produced() -> None:
    """The quantile rule: a bound is the smallest resampled value whose cumulative share
    reaches the quantile, so it is always a value some resample produced and never a point
    between two of them.  At 2,000 resamples neighbouring order statistics coincide and
    CAL9_1 cannot see the difference; at five they rarely do.

    On a cell where every task is all-pass or all-fail, every resample's pass@1 is a multiple
    of 1/S, so every bound must be one too.  An interpolated quantile lands between."""
    counts = (0, 0, N, N, N)
    scored = cal().scored(cell_from(counts))
    for seed in range(40):
        bounds = cal().cluster_bootstrap(scored, cal().pass_at_1, resamples=5, seed=seed)
        for bound in bounds:
            assert bound * len(counts) == pytest.approx(round(bound * len(counts))), (seed, bounds)


