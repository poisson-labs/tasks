def expect_pass_at_1(counts: Sequence[int], n: int = N) -> float:
    """CAL6: the mean over tasks of each task's mean indicator.  Task-weighted."""
    return sum(c / n for c in counts) / len(counts)


def expect_pass_at_k_closed(counts: Sequence[int], k: int, n: int = N) -> float:
    """CAL7's closed form: `1 - C(n-c, k)/C(n, k)`, averaged over tasks."""
    assert k <= n
    return sum(1.0 - (math.comb(n - c, k) / math.comb(n, k)) for c in counts) / len(counts)


def expect_pass_at_k_exhaustive(counts: Sequence[int], k: int, n: int = N) -> float:
    """CAL7 again, derived a second way and never from the first: over **every** `C(n, k)`
    subset of a task's attempts, the fraction in which at least one attempt passed."""
    assert k <= n
    total = 0.0
    for passes in counts:
        attempts = [True] * passes + [False] * (n - passes)
        subsets = list(itertools.combinations(attempts, k))
        total += sum(1 for subset in subsets if any(subset)) / len(subsets)
    return total / len(counts)


def exact_cluster_bootstrap(counts: Sequence[int], n: int = N) -> list[float]:
    """The **exact** task-clustered resampling distribution of pass@1 for a small cell: every
    one of the `S**S` equally likely resamples of S tasks with replacement, each carrying its
    whole block of attempts.  Only tractable for S = 3 (27) or S = 4 (256); the tests use it
    to check that the Monte Carlo bootstrap converges to a known answer."""
    size = len(counts)
    assert size <= 4, "enumeration is exponential; keep the fixture at S <= 4"
    out: list[float] = []
    for draw in itertools.product(range(size), repeat=size):
        out.append(sum(counts[i] / n for i in draw) / size)
    return sorted(out)


def exact_quantile(sorted_values: Sequence[float], q: float) -> float:
    """The `q` quantile of an exactly enumerated discrete distribution: the smallest value
    whose cumulative share reaches `q`.

    **Not the nearest-rank or the floor rule.**  Both are wrong on a distribution with few
    atoms -- at S = 3 the largest of the 27 resamples carries 1/27 = 3.7% of the mass, which
    is more than the 2.5% in the upper tail, so the 97.5 quantile *is* that largest value and
    a floor rule reports the one below it.  Measured: with this rule the Monte Carlo bootstrap
    at 2,000 resamples reproduces the enumerated quantile **exactly** on every fixture below,
    across five seeds -- so CAL9_1 asserts equality and not a tolerance."""
    return sorted_values[min(len(sorted_values) - 1, max(0, math.ceil(q * len(sorted_values)) - 1))]


# CAL6's separating fixture, and the reason it has to exist.  **At equal `n`, weighting by
# task and weighting by attempt give the identical number**: the mean of `c / n` over tasks
# is the sum of `c` over `S * n` attempts.  So a cell where every task kept its five
# attempts cannot tell mutant M1 from the truth, and the only fixture that can is one with
# unequal surviving `n` after CAL16's exclusions.  Each pair is `(passes, surviving attempts)`;
# the missing attempts carry instrument labels and leave the denominator.
UNEQUAL_SURVIVORS = ((5, 5), (4, 5), (0, 1), (0, 2), (1, 4), (3, 5), (0, 1), (2, 3))


def cell_with_exclusions(
    survivors: Sequence[tuple[int, int]] = UNEQUAL_SURVIVORS,
    *,
    n: int = N,
    arm: str = "depth:d3",
) -> list[Any]:
    """A cell whose tasks kept unequal numbers of attempts: task `i` ran `n`, of which
    `survivors[i][1]` were scored and the rest carry an instrument label."""
    out: list[Any] = []
    for index, (passes, kept) in enumerate(survivors):
        assert 0 <= passes <= kept <= n, (index, passes, kept, n)
        for attempt in range(n):
            if attempt < kept:
                out.append(
                    record(
                        task_id=f"u{index:03d}", seed=2000 + index, attempt=attempt,
                        strict=attempt < passes, arm=arm,
                    )
                )
            else:
                out.append(
                    record(
                        task_id=f"u{index:03d}", seed=2000 + index, attempt=attempt,
                        strict=False, leaky=False, arm=arm,
                        label=INSTRUMENT_LABELS[attempt % len(INSTRUMENT_LABELS)],
                    )
                )
    return out


def expect_task_weighted(survivors: Sequence[tuple[int, int]]) -> float:
    return sum(p / kept for p, kept in survivors) / len(survivors)


def expect_attempt_weighted_unequal(survivors: Sequence[tuple[int, int]]) -> float:
    """Mutant M1's answer on the same fixture."""
    return sum(p for p, _ in survivors) / sum(kept for _, kept in survivors)


