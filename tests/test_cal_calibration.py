@pytest.mark.parametrize("k", range(1, N + 1))
def test_cal7_6_pass_at_k_scores_the_strict_reward_and_not_the_leaky_one(k: int) -> None:
    """**A mutant survived every other CAL7 test**: scoring `leaky` instead of `strict` is
    invisible on any fixture where the two agree, and in the ordinary fixtures they agree by
    construction (G6: strict `passed` implies `leaky_pass`).

    Here they are made to differ.  Every attempt is a leaky pass -- an `overshoot`, which
    leaky accepts and strict does not -- and only the first two of each task's five are strict
    passes.  pass@k must read the reward X4 defines, so the answer is the strict one at every
    k, and the leaky one is a different number."""
    counts_strict = (2, 2, 2, 2, 2, 2)
    cell: list[Any] = []
    for index, passes in enumerate(counts_strict):
        for attempt in range(N):
            strict = attempt < passes
            cell.append(record(
                task_id=f"lk{index:03d}", seed=3000 + index, attempt=attempt,
                strict=strict, leaky=True, label="passed" if strict else "overshoot",
            ))
    got = cal().pass_at_k(cal().scored(cell), k)
    assert got == pytest.approx(expect_pass_at_k_closed(counts_strict, k))
    leaky_answer = expect_pass_at_k_closed((N,) * len(counts_strict), k)
    assert leaky_answer == pytest.approx(1.0)
    # The two answers separate only while `k` can still miss every passing attempt: with
    # c = 2 of n = 5, pass@k reaches 1.0 at k = 4 because every 4-subset contains a pass.
    # So the inequality is asserted where it is a fact -- k <= n - c -- and the equality
    # above, which holds at every k, is what carries the rest.
    if k <= N - counts_strict[0]:
        assert got != pytest.approx(leaky_answer), (
            "pass@k is scoring the leaky predicate; X4's reward is the strict one"
        )
    else:
        assert got == pytest.approx(1.0)


